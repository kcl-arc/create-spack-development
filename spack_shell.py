#!/usr/bin/env python3
"""
Start an interactive shell in the Spack container with a Spack environment
active, using the same binds as the batch jobs.

On a node where singularity is available (e.g. inside an srun session) the
container starts directly; otherwise the shell is started on a compute node
with srun (within the current allocation if SLURM_JOB_ID is set).

Run directly (not via sbatch). Reads var/setup_state.yaml (written by setup.py).
"""

import os
import shutil
import sys

try:
    from er_spack_common import (
        build_shell_parser,
        constraint_for,
        container_binds,
        load_setup_state,
        parse_args,
        prepare_envs,
        quote_cmd,
        resolve_env,
    )
except ModuleNotFoundError as e:
    if e.name != "er_spack_common":
        raise
    sys.exit(
        "Cannot import er_spack_common. Run this script directly from the "
        "create-spack-development checkout; it starts its own Slurm session, so "
        "don't submit it with sbatch."
    )

SHELL_RC = """\
# Generated by spack_shell.py for Spack environment "{env}".
source /opt/spack/share/spack/setup-env.sh
spack env activate {env}
PS1='[{env}] \\w \\$ '
echo "Spack environment '{env}' is active ('exit' to leave)."
"""


def shell_command(args, state, env, rc_path):
    singularity = [
        "singularity",
        "exec",
        "--env",
        f"SPACK_USER_CONFIG_PATH={state['spack_user_config_path']}",
    ]
    for path in container_binds(state):
        singularity += ["--bind", f"{path}:{path}"]
    singularity += ["--pwd", state["repo_dir"], state["sif_path"], "bash", "--rcfile", rc_path, "-i"]

    if shutil.which("singularity"):
        return singularity, "singularity is available here: starting the container directly"

    # bash -l on the compute node gives its PATH, where singularity lives.
    remote = ["--pty", "bash", "-l", "-c", "exec " + quote_cmd(singularity)]
    if os.environ.get("SLURM_JOB_ID"):
        # A single task, so --pty doesn't start one shell per task.
        cmd = ["srun", "--ntasks=1"] + args.passthrough + remote
        return cmd, f"inside allocation {os.environ['SLURM_JOB_ID']}: srun within it"
    cmd = ["srun", "-p", args.partition, "--ntasks=1", "--cpus-per-task=4", "--mem-per-cpu=4096"]
    constraint = constraint_for(env, args)
    if constraint:
        cmd += ["--constraint", constraint]
    cmd += args.passthrough + remote
    return cmd, "starting an interactive session with srun"


def main():
    parser = build_shell_parser("Interactive shell in the Spack container with an environment active")
    args = parse_args(parser)
    state = load_setup_state()
    env = resolve_env(args)
    prepare_envs([env], state, write=not args.dry_run)

    rc_path = os.path.join(state["var_dir"], "shell", f"{env}.bashrc")
    rc_text = SHELL_RC.format(env=env)
    cmd, how = shell_command(args, state, env, rc_path)

    if args.dry_run:
        print(f"# {how}")
        print(f"# {rc_path}:")
        print(rc_text)
        print("$ " + quote_cmd(cmd))
        return

    os.makedirs(os.path.dirname(rc_path), exist_ok=True)
    with open(rc_path, "w") as fh:
        fh.write(rc_text)
    print(f"{how.capitalize()}...")
    try:
        os.execvp(cmd[0], cmd)
    except FileNotFoundError:
        sys.exit(f"{cmd[0]} not found: run this on a cluster login or compute node.")


if __name__ == "__main__":
    main()
